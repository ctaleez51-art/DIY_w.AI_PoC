def 소리만들기(번호, 글):
    길 = os.path.join(소리방, f"말{번호}.wav")
    if os.path.exists(길):
        return 길
    본 = f'''Add-Type -AssemblyName System.Speech
$s = New-Object System.Speech.Synthesis.SpeechSynthesizer
$s.SelectVoice("Microsoft Heami Desktop")
$s.SetOutputToWaveFile("{길}")
$s.Speak("{글}")
$s.Dispose()'''
    subprocess.run(["powershell", "-NoProfile", "-Command", 본], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return 길


def 받아적기(길):
    경계 = "----boundary1234"
    with open(길, "rb") as f:
        소리 = f.read()
    몸 = (f"--{경계}\r\nContent-Disposition: form-data; name=\"audio\"; "
          f"filename=\"말.wav\"\r\nContent-Type: audio/wav\r\n\r\n").encode() + 소리 + \
         f"\r\n--{경계}--\r\n".encode()
    청 = urllib.request.Request(코랩 + "/stt", 몸,
                               {"Content-Type": f"multipart/form-data; boundary={경계}"})
    시작 = time.time()
    with urllib.request.urlopen(청, timeout=300) as 답:
        나온것 = json.load(답)
    return 나온것["텍스트"], round(time.time() - 시작, 1)


def 칸나누기(말):
    몸 = json.dumps({"model": "gemma3:4b",
                    "prompt": 지시문틀.format(오늘=오늘, 어제=어제, 말=말),
                    "format": "json", "stream": False,
                    "options": {"temperature": 0}}).encode()
    청 = urllib.request.Request("http://127.0.0.1:11434/api/generate", 몸,
                               {"Content-Type": "application/json"})
    시작 = time.time()
    with urllib.request.urlopen(청, timeout=300) as 답:
        글 = json.load(답)["response"]
    try:
        생것 = json.loads(글)
    except Exception:
        생것 = {}
    return 생것, round(time.time() - 시작, 1)


def 숫자로(값):
    if isinstance(값, (int, float)) and not isinstance(값, bool):
        return int(값)
    글 = re.sub(r"[^0-9]", "", str(값 or ""))
    return int(글) if 글 else ""


